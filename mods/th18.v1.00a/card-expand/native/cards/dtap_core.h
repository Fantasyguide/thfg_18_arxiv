#ifndef DTAP_CORE_H
#define DTAP_CORE_H

/* ★★★ 2026-10-14（P23）：**「完整双击」纯逻辑状态机**（共享件，纯函数、可离线单测 ✓）。
 *
 * 来源 = **116（season_core）2026-09-29 的实现，逐字照搬** ✓ —— 那次是 owner 口径（原话）：
 *   「算了，改成**双击 Z** 吧，**必须是完整的双击**：**不按 Z，按 Z，放开，再按**」✓
 * 本次（P23）是 owner 的第二次要求：**111 魔理沙特技切换自机也改成双击 Z、与 116 一致** ✓
 *   ⇒ 于是把这份状态机**抽成共享件**，两卡**同一份实现**（避免"同一类表现、做法茫茫多" ✗）。
 *
 * ## 语义（❓自定，逐条）
 * 1. **完整双击**：手势 = 按下 → 放开 → **再按下**；触发帧 = **第二次按下的那一帧** ✓。
 * 2. **窗口 `window` 帧**（默认 `CE_DTAP_WINDOW_DEFAULT` = **8**）：从**第一次按下**那一帧起算 ✓；
 *    整个手势必须在窗内完成、两个相位各至少 1 帧 ⇒
 *    「按住很久 → 放开 → 再按」**不触发** ✓（刻意选的：Z 在 TH18 是**开火键**，
 *    「停火 → 再开火」日常高频，若把长按也算起手会大量误切 ✗）。
 *    ★ 8 帧 = owner 口径「**双击窗口参考 111 灵梦特技穿墙**」⇒ TH11 缺口瞬移的二次窗口
 *      （`th11:0x430e50` 状态机；`engine/input/th11/01-special-detection.md` §3）✓；
 *      ⚠ 对齐点：TH11 那个计数器也是**从第一次按下起算**（≥9 帧即作废）✓。
 * 3. **去重**：一次手势只给一次 `1`（触发后要等这次松手才重新武装 ✓）⇒
 *    「按-放-按」= 1 次、「按-放-按-放-按-放-按」= 2 次、**三连按 = 1 次**（不会一次给两档 ✓）。
 *
 * ## 状态
 * `0` 空闲 / `1` 第一次按下（等放开）/ `2` 已松手（等第二次按下）/ `3` 第一次按太久（等松手作废）/
 * `4` 已触发（等松手重新武装）。*/

#include <stdint.h>

#define CE_DTAP_WINDOW_DEFAULT 8

typedef struct {
    uint8_t state;      /* 见上面的状态表 ✓ */
    uint8_t win;        /* 剩余窗口（帧）*/
    uint8_t window;     /* 窗口长度（帧）；`0` ⇒ 用 `CE_DTAP_WINDOW_DEFAULT` ✓（于是 memset 后的零值也安全 ✓）*/
} ce_dtap_t;

/* 清零 + 设窗口（`window <= 0` ⇒ 用默认 ✓）。卡初始化 / 删卡时调 ✓；
 * ⚠ 也可以完全不调 —— `ce_dtap_tick()` 对 `window == 0` 会回落到默认值 ✓（卡的 `memset` 已够 ✓）。*/
void ce_dtap_init(ce_dtap_t *d, int window);

/* 每帧推进一次；`held` = 本帧按键是否按住（非 0 即按住 ✓）。
 * 返回 `1` = **本帧触发一次** ✓（不连发 ✓）；`d == NULL` ⇒ 返回 0 ✓。*/
int ce_dtap_tick(ce_dtap_t *d, int held);

#endif /* DTAP_CORE_H */
